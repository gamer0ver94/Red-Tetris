export function get_next_rotation(rotation:RotationType):RotationType{
    return ((rotation + 1) % 4) as RotationType
}

export function get_prev_rotation(rotation:RotationType):RotationType{
    return ((rotation + 3) % 4) as RotationType
}

export function get_shape(
    type:PieceType,
    rotation:RotationType,
):BoardType{
    return ROTATION_TABLES[type][rotation].map((row) => [...row]);
}

export function get_kicks(
    type:PieceType,
    from:RotationType,
    to:RotationType
):KickType[]{
    const key = `${from}>${to}` as RotationTransition;
    let table;

    if(type === "O")
        table = KICK_TABLES.O[key];
    else if(type === "I")
        table =  KICK_TABLES.I[key];
    else 
        table = KICK_TABLES.JLSTZ[key];
    
    return table.map((kick) => [...kick] as KickType);
}
