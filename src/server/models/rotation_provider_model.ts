    public static get_shape(type:PieceType, rotation:RotationType):BoardType{
        return this.rotation_tables[type][rotation] as BoardType
    }

    public static get_next_rotation(rotation:RotationType):RotationType{
        return ((rotation + 1) % 4) as RotationType;
    }

    public static get_prev_rotation(rotation:RotationType):RotationType{
        return ((rotation + 3) % 4) as RotationType;
    }

    public static get_kicks(
        type:PieceType,
        from:RotationType,
        to:RotationType,
    ):KickType[]{

        const key = `${from}>${to}` as RotationTransition;

        if(type === "O")
            return this.kick_tables.O[key] as KickType[];

        if(type === "I")
            return this.kick_tables.I[key] as KickType[];
        return this.kick_tables.JLSTZ[key] as KickType[];
    }
    
